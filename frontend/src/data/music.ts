/** 计算余弦相似度 */
function cosineSimilarity(vec1: number[], vec2: number[]): number {
  let dotProduct = 0
  let norm1 = 0
  let norm2 = 0
  const len = Math.min(vec1.length, vec2.length)
  for (let i = 0; i < len; i++) {
    const v1 = vec1[i] ?? 0
    const v2 = vec2[i] ?? 0
    dotProduct += v1 * v2
    norm1 += v1 * v1
    norm2 += v2 * v2
  }
  const denom = Math.sqrt(norm1) * Math.sqrt(norm2)
  return denom === 0 ? 0 : dotProduct / denom
}

