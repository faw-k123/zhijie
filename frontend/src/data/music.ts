/** 匹配文化圈层 */
export function matchCulturalCircles(userVector: number[], topK: number = 5): { name: string; similarity: number; factors: number[] }[] {
  const results = culturalCircles.map((circle) => ({
    name: circle.name,
    similarity: Math.round(cosineSimilarity(userVector, circle.factors) * 100),
    factors: circle.factors,
  }))

  return results.sort((a, b) => b.similarity - a.similarity).slice(0, topK)
}

